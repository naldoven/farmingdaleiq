insert into public.catering_menu_items (
  name, category, pickup_price_cents, delivery_price_cents, components, scaling_rules, active
)
select name, category, pickup_price_cents, delivery_price_cents, '[]'::jsonb, '[]'::jsonb, true
from catalog
on conflict (name) do update
set
  category = excluded.category,
  pickup_price_cents = excluded.pickup_price_cents,
  delivery_price_cents = excluded.delivery_price_cents,
  active = true;

-- Retire the original placeholder choices so staff only selects Farmingdale's
-- photographed catalog. Historical order rows continue to retain their link.
