-- Farmingdale's pickup and delivery catering catalog, transcribed from the
-- store's catering ordering screens. Prices are stored as integer cents so a
-- catalog edit can never introduce floating-point rounding into order records.

alter table public.catering_menu_items
  add column if not exists pickup_price_cents integer,
  add column if not exists delivery_price_cents integer;

alter table public.catering_menu_items
  add constraint catering_menu_items_pickup_price_cents_check
    check (pickup_price_cents is null or pickup_price_cents >= 0),
  add constraint catering_menu_items_delivery_price_cents_check
    check (delivery_price_cents is null or delivery_price_cents >= 0);

create unique index if not exists catering_menu_items_name_unique
  on public.catering_menu_items (name);

